/**
 * EX03 - operations et le cast (conversion)
 */
public class Ex03_Operations {
    public static void main(String[] args) {
        int a = 15;
        int b = 4;

        System.out.println("a + b = " + (a + b));
        System.out.println("a - b = " + (a - b));
        System.out.println("a * b = " + (a * b));
        System.out.println("a / b = " + (a / b));
        System.out.println("a % b = " + (a % b));
        System.out.println("a / (double) b = " + (a / (double) b));  // cast
    }
}